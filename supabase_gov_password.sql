-- 1) Trilha de auditoria: ninguem le nem escreve direto; so as funcoes abaixo.
create table if not exists public.audit_log (
    id bigint generated by default as identity primary key,
    actor uuid not null default auth.uid(),
    actor_email text,
    action text not null,
    client_id bigint,
    created_at timestamptz not null default now()
);
alter table public.audit_log enable row level security;
revoke all on public.audit_log from anon, authenticated;

-- 2) Senhas cifradas ficam numa tabela propria, sem nenhum acesso direto para a API.
create table if not exists public.client_secrets (
    client_id bigint primary key references public.clients(id) on delete cascade,
    gov_password_enc bytea not null,
    updated_at timestamptz not null default now()
);
alter table public.client_secrets enable row level security;
revoke all on public.client_secrets from anon, authenticated;

-- Indicador (nao sensivel) para as telas saberem se existe senha, sem le-la.
alter table public.client_private
    add column if not exists has_gov_password boolean not null default false;

-- 3) Chave: vem do Vault; se faltar, falha alto (nunca grava "null" no lugar da senha).
create or replace function private.gov_key()
returns text
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    k text;
begin
    select decrypted_secret into k
    from vault.decrypted_secrets
    where name = 'gov_password_key'
    limit 1;
    if k is null then
        raise exception 'segredo gov_password_key ausente no Vault' using errcode = '55000';
    end if;
    return k;
end;
$$;
revoke execute on function private.gov_key() from public, anon, authenticated;

-- 4) Transicao: se o app antigo ainda gravar a senha em texto puro, ela e cifrada na hora.
create or replace function private.encrypt_gov_password_on_write()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    if coalesce(btrim(new.gov_password), '') <> ''
       and (tg_op = 'INSERT' or new.gov_password is distinct from old.gov_password) then
        insert into public.client_secrets (client_id, gov_password_enc, updated_at)
        values (new.client_id, extensions.pgp_sym_encrypt(new.gov_password, private.gov_key()), now())
        on conflict (client_id) do update
            set gov_password_enc = excluded.gov_password_enc, updated_at = now();
        new.has_gov_password := true;
    end if;
    return new;
end;
$$;
revoke execute on function private.encrypt_gov_password_on_write() from public, anon, authenticated;

drop trigger if exists client_private_encrypt_gov_password on public.client_private;
create trigger client_private_encrypt_gov_password
    before insert or update of gov_password on public.client_private
    for each row execute function private.encrypt_gov_password_on_write();

-- 5) Copia inicial das senhas que ja existem (nao sobrescreve o que ja estiver cifrado).
insert into public.client_secrets (client_id, gov_password_enc)
select cp.client_id, extensions.pgp_sym_encrypt(cp.gov_password, private.gov_key())
from public.client_private cp
where coalesce(btrim(cp.gov_password), '') <> ''
on conflict (client_id) do nothing;

update public.client_private cp
set has_gov_password = exists (select 1 from public.client_secrets s where s.client_id = cp.client_id)
where cp.has_gov_password is distinct from
      exists (select 1 from public.client_secrets s where s.client_id = cp.client_id);

-- 6) Funcoes de acesso (as unicas portas para a senha).
create or replace function public.set_gov_password(p_client_id bigint, p_value text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    has_value boolean := coalesce(btrim(p_value), '') <> '';
begin
    if not private.can_manage() then
        raise exception 'sem permissao' using errcode = '42501';
    end if;

    if has_value then
        insert into public.client_secrets (client_id, gov_password_enc, updated_at)
        values (p_client_id, extensions.pgp_sym_encrypt(p_value, private.gov_key()), now())
        on conflict (client_id) do update
            set gov_password_enc = excluded.gov_password_enc, updated_at = now();
    else
        delete from public.client_secrets where client_id = p_client_id;
    end if;

    insert into public.client_private (client_id, has_gov_password, updated_at)
    values (p_client_id, has_value, now())
    on conflict (client_id) do update
        set has_gov_password = excluded.has_gov_password, updated_at = now();

    -- Antes do finalize a coluna de texto puro ainda existe: zera para nao ficar senha velha.
    if exists (select 1 from information_schema.columns
               where table_schema = 'public' and table_name = 'client_private'
                 and column_name = 'gov_password') then
        execute 'update public.client_private set gov_password = null where client_id = $1'
            using p_client_id;
    end if;

    insert into public.audit_log (actor, actor_email, action, client_id)
    values (auth.uid(), auth.jwt() ->> 'email', 'set_gov_password', p_client_id);
end;
$$;

create or replace function public.reveal_gov_password(p_client_id bigint)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
    result text;
begin
    if not (private.has_sector('Comercial')
            or private.has_sector('Preenchimento')
            or private.has_sector(U&'Revis\00e3o')) then
        raise exception 'sem permissao' using errcode = '42501';
    end if;

    select extensions.pgp_sym_decrypt(s.gov_password_enc, private.gov_key())
    into result
    from public.client_secrets s
    where s.client_id = p_client_id;

    insert into public.audit_log (actor, actor_email, action, client_id)
    values (auth.uid(), auth.jwt() ->> 'email', 'reveal_gov_password', p_client_id);

    return result;
end;
$$;

revoke execute on function public.set_gov_password(bigint, text) from public, anon;
revoke execute on function public.reveal_gov_password(bigint) from public, anon;
grant execute on function public.set_gov_password(bigint, text) to authenticated;
grant execute on function public.reveal_gov_password(bigint) to authenticated;
